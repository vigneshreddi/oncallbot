param([string]$Remote = 'origin', [string]$Branch = 'main', [string]$PythonExecutable = 'python', [switch]$Revert)
$ErrorActionPreference = 'Stop'
Push-Location (Split-Path $PSScriptRoot -Parent)
try {
  $output = 'config/services.deployed.yaml'
  if ($Revert) {
    Remove-Item -LiteralPath $output -ErrorAction SilentlyContinue
    Write-Output 'Back to local-demo. Run up.ps1, index-code.ps1 and start-investigator.ps1.'
    return
  }
  $dirty = git status --porcelain --untracked-files=all
  if ($LASTEXITCODE -ne 0) { throw 'Cannot read Git status.' }
  if ($dirty) { throw 'Uncommitted or untracked files exist. Commit and push first; the deployed code must equal a pushed commit.' }
  git fetch --quiet $Remote $Branch
  if ($LASTEXITCODE -ne 0) { throw "Cannot fetch $Remote/$Branch." }
  $head = (git rev-parse HEAD).Trim()
  $remoteHead = (git rev-parse "$Remote/$Branch").Trim()
  if ($head -ne $remoteHead) { throw "HEAD ($head) is not $Remote/$Branch ($remoteHead). Push or pull first." }
  $script = @'
import sys, yaml
with open('config/services.yaml', encoding='utf-8') as stream:
    data = yaml.safe_load(stream)
for service in data['services']:
    service['prod_commit'] = sys.argv[1]
    service['commit_kind'] = 'git'
with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as stream:
    stream.write('# Generated by scripts/use-pushed-commit.ps1; git-ignored. Delete with -Revert.\n')
    yaml.safe_dump(data, stream, sort_keys=False)
'@
  & $PythonExecutable -c $script $head $output
  if ($LASTEXITCODE -ne 0) { throw 'Cannot write the deployed service registry.' }
  Write-Output "prod_commit set to $head ($Remote/$Branch) in $output."
  Write-Output 'Next: ./scripts/up.ps1; ./scripts/index-code.ps1; ./scripts/start-investigator.ps1'
} finally { Pop-Location }
